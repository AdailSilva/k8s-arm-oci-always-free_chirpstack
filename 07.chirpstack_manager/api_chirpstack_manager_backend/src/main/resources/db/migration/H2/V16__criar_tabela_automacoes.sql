-- =====================================================================
--  V16 - Automações: regra de alerta dispara uma ação
--
--  tb_automacao .. quando um alerta da "regra_id" ABRE (gatilho
--                  ALERTA_ABERTO) ou é RESOLVIDO (ALERTA_RESOLVIDO),
--                  executa um comando ou uma cena. Com
--                  "mesmo_dispositivo" = TRUE o comando vai para o
--                  dispositivo que disparou o alerta (útil em regras que
--                  valem para todos). "intervalo_minimo_s" evita que um
--                  valor oscilando no limite acione a carga sem parar.
-- =====================================================================
CREATE TABLE tb_automacao (
    id                   BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                 VARCHAR(120)  NOT NULL,
    regra_id             BIGINT        NOT NULL,
    gatilho              VARCHAR(20)   NOT NULL,
    alvo                 VARCHAR(10)   NOT NULL,
    mesmo_dispositivo    BOOLEAN       NOT NULL DEFAULT FALSE,
    dispositivo_id       BIGINT,
    tipo                 VARCHAR(30),
    parametros           TEXT,
    cena_id              BIGINT,
    intervalo_minimo_s   INTEGER       NOT NULL DEFAULT 300,
    ativo                BOOLEAN       NOT NULL DEFAULT TRUE,
    ultima_execucao_em   TIMESTAMP WITH TIME ZONE,
    criado_em            TIMESTAMP WITH TIME ZONE NOT NULL,
    atualizado_em        TIMESTAMP WITH TIME ZONE NOT NULL,
    atualizado_por       VARCHAR(160),
    CONSTRAINT fk_tb_automacao_regra FOREIGN KEY (regra_id) REFERENCES tb_regra_alerta (id) ON DELETE CASCADE,
    CONSTRAINT fk_tb_automacao_dispositivo FOREIGN KEY (dispositivo_id) REFERENCES tb_dispositivo (id) ON DELETE CASCADE,
    CONSTRAINT fk_tb_automacao_cena FOREIGN KEY (cena_id) REFERENCES tb_cena (id) ON DELETE CASCADE,
    CONSTRAINT ck_tb_automacao_gatilho CHECK (gatilho IN ('ALERTA_ABERTO', 'ALERTA_RESOLVIDO')),
    CONSTRAINT ck_tb_automacao_alvo CHECK ((alvo = 'COMANDO' AND tipo IS NOT NULL AND (mesmo_dispositivo OR dispositivo_id IS NOT NULL))
                                           OR (alvo = 'CENA' AND cena_id IS NOT NULL)),
    CONSTRAINT ck_tb_automacao_intervalo CHECK (intervalo_minimo_s BETWEEN 0 AND 86400)
);
CREATE INDEX idx_tb_automacao_regra ON tb_automacao (regra_id, gatilho, ativo);
