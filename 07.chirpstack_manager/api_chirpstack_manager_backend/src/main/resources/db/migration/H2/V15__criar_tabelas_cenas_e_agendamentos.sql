-- =====================================================================
--  V15 - Cenas e agendamentos
--
--  tb_cena ......... conjunto de comandos disparados juntos (um botão).
--  tb_cena_item .... um comando da cena (dispositivo, tipo e parâmetros
--                    em JSON), na ordem de "ordem".
--  tb_agendamento .. executa um comando ou uma cena:
--                    recorrencia UNICA ... uma vez em "executar_em";
--                    recorrencia SEMANAL . em "horario" (hora local) nos
--                    "dias_semana" (bits: 1 = segunda ... 64 = domingo).
--                    "validade_min" e "max_tentativas" viram a política
--                    de novas tentativas dos comandos gerados.
-- =====================================================================
CREATE TABLE tb_cena (
    id                 BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome               VARCHAR(120)  NOT NULL,
    descricao          VARCHAR(300),
    criado_em          TIMESTAMP WITH TIME ZONE NOT NULL,
    atualizado_em      TIMESTAMP WITH TIME ZONE NOT NULL,
    atualizado_por     VARCHAR(160),
    CONSTRAINT uk_tb_cena_nome UNIQUE (nome)
);

CREATE TABLE tb_cena_item (
    id                 BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cena_id            BIGINT        NOT NULL,
    ordem              INTEGER       NOT NULL,
    dispositivo_id     BIGINT        NOT NULL,
    tipo               VARCHAR(30)   NOT NULL,
    parametros         TEXT,
    CONSTRAINT fk_tb_cena_item_cena FOREIGN KEY (cena_id) REFERENCES tb_cena (id) ON DELETE CASCADE,
    CONSTRAINT fk_tb_cena_item_dispositivo FOREIGN KEY (dispositivo_id) REFERENCES tb_dispositivo (id) ON DELETE CASCADE
);
CREATE INDEX idx_tb_cena_item_cena ON tb_cena_item (cena_id, ordem);

CREATE TABLE tb_agendamento (
    id                   BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                 VARCHAR(120)  NOT NULL,
    alvo                 VARCHAR(10)   NOT NULL,
    dispositivo_id       BIGINT,
    tipo                 VARCHAR(30),
    parametros           TEXT,
    cena_id              BIGINT,
    recorrencia          VARCHAR(10)   NOT NULL,
    executar_em          TIMESTAMP WITH TIME ZONE,
    horario              TIME,
    dias_semana          INTEGER       NOT NULL DEFAULT 127,
    validade_min         INTEGER       NOT NULL DEFAULT 60,
    max_tentativas       INTEGER       NOT NULL DEFAULT 5,
    ativo                BOOLEAN       NOT NULL DEFAULT TRUE,
    proxima_execucao_em  TIMESTAMP WITH TIME ZONE,
    ultima_execucao_em   TIMESTAMP WITH TIME ZONE,
    criado_em            TIMESTAMP WITH TIME ZONE NOT NULL,
    atualizado_em        TIMESTAMP WITH TIME ZONE NOT NULL,
    atualizado_por       VARCHAR(160),
    CONSTRAINT fk_tb_agendamento_dispositivo FOREIGN KEY (dispositivo_id) REFERENCES tb_dispositivo (id) ON DELETE CASCADE,
    CONSTRAINT fk_tb_agendamento_cena FOREIGN KEY (cena_id) REFERENCES tb_cena (id) ON DELETE CASCADE,
    CONSTRAINT ck_tb_agendamento_alvo CHECK ((alvo = 'COMANDO' AND dispositivo_id IS NOT NULL AND tipo IS NOT NULL)
                                             OR (alvo = 'CENA' AND cena_id IS NOT NULL)),
    CONSTRAINT ck_tb_agendamento_recorrencia CHECK ((recorrencia = 'UNICA' AND executar_em IS NOT NULL)
                                                    OR (recorrencia = 'SEMANAL' AND horario IS NOT NULL)),
    CONSTRAINT ck_tb_agendamento_dias CHECK (dias_semana BETWEEN 1 AND 127),
    CONSTRAINT ck_tb_agendamento_validade CHECK (validade_min BETWEEN 1 AND 43200),
    CONSTRAINT ck_tb_agendamento_tentativas CHECK (max_tentativas BETWEEN 1 AND 50)
);
CREATE INDEX idx_tb_agendamento_proxima ON tb_agendamento (ativo, proxima_execucao_em);
